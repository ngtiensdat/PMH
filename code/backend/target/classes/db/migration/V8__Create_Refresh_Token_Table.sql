BEGIN
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE PMH_REFRESH_TOKENS CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
END;
;

CREATE TABLE PMH_REFRESH_TOKENS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(50 CHAR) NOT NULL,
    TOKEN_HASH VARCHAR2(255 CHAR) NOT NULL UNIQUE,
    EXPIRY_DATE TIMESTAMP NOT NULL,
    REVOKED NUMBER(1) DEFAULT 0 NOT NULL,
    CREATED_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- Index tra cứu theo Username (TOKEN_HASH đã được Oracle tự đánh Index duy nhất từ UNIQUE)
CREATE INDEX IDX_RT_USERNAME ON PMH_REFRESH_TOKENS(USERNAME);
