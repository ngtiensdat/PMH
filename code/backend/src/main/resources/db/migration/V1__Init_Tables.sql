-- 8. Bảng PMH_AUDIT_LOG (Nhật ký lịch sử thao tác)
-- ====================================================================
CREATE TABLE PMH_AUDIT_LOG (
    ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MODULE        VARCHAR2(50 CHAR)   NOT NULL,   -- 'GROUP_CATEGORY' | 'COMPONENT'
    RECORD_ID     VARCHAR2(100 CHAR)  NOT NULL,   -- ID hoặc COMPONENT_CODE của bản ghi
    ACTION        VARCHAR2(100 CHAR)  NOT NULL,   -- 'Tạo mới' | 'Cập nhật' | 'Xóa' | 'Gửi duyệt' | 'Phê duyệt' | 'Từ chối' | 'Hủy duyệt'
    PERFORMED_BY  VARCHAR2(100 CHAR)  NOT NULL,   -- Username người thực hiện
    ACTION_DATE   DATE DEFAULT SYSDATE NOT NULL,  -- Thời điểm thực hiện
    OLD_DATA      CLOB,                            -- JSON dữ liệu trước khi thay đổi
    NEW_DATA_LOG  CLOB,                            -- JSON dữ liệu sau khi thay đổi
    DESCRIPTION   VARCHAR2(4000 CHAR),             -- Mô tả chi tiết hành động
    STATUS_BEFORE NUMBER(1),                       -- Trạng thái trước (1,3,4,5,7)
    STATUS_AFTER  NUMBER(1),                       -- Trạng thái sau
    IP_ADDRESS    VARCHAR2(100 CHAR)               -- Địa chỉ IP của client gửi yêu cầu
);

-- Index cho query hiệu quả theo module + record
CREATE INDEX IDX_AUDIT_MODULE_RECORD ON PMH_AUDIT_LOG (MODULE, RECORD_ID);
-- Index cho sort theo thời gian
CREATE INDEX IDX_AUDIT_ACTION_DATE   ON PMH_AUDIT_LOG (ACTION_DATE DESC);

