-- 1. Tạo bảng PMH_COMPONENTS (Bảng cấu phần xử lý - Bảng cha)
CREATE TABLE PMH_COMPONENTS (
    COMPONENT_CODE   VARCHAR2(50 CHAR)   NOT NULL PRIMARY KEY,
    COMPONENT_NAME   VARCHAR2(255 CHAR)  NOT NULL,
    MESSAGE_TYPE     VARCHAR2(100 CHAR),  -- Chuẩn tin điện: ISO20022, MT, MX...
    CONNECTION_METHOD VARCHAR2(100 CHAR), -- Phương thức kết nối: API, MQ, SFTP...
    CHECK_TOKEN      VARCHAR2(1 CHAR) DEFAULT 'N', -- Y: Có kiểm tra token, N: Không
    DESCRIPTION      VARCHAR2(4000 CHAR),
    STATUS           NUMBER(1) DEFAULT 1 NOT NULL, -- 1: Mới, 3: Chờ duyệt, 4: Đã duyệt, 5: Từ chối, 7: Hủy duyệt
    IS_ACTIVE        NUMBER(1) DEFAULT 1 NOT NULL, -- 0: Không hoạt động, 1: Hoạt động
    IS_DISPLAY       NUMBER(1) DEFAULT 1 NOT NULL, -- 1: Chưa duyệt (cho phép xóa), 2: Đã duyệt
    NEW_DATA         VARCHAR2(4000 CHAR),
    EFFECTIVE_DATE   DATE NOT NULL,
    END_EFFECTIVE_DATE DATE,
    CREATED_BY       VARCHAR2(50 CHAR),
    CREATED_DATE     DATE DEFAULT SYSDATE,
    UPDATED_BY       VARCHAR2(50 CHAR),
    UPDATED_DATE     DATE DEFAULT SYSDATE
);

-- 2. Tạo bảng chính PMH_GROUP_CATEGORY (Tham số danh mục theo nhóm)
CREATE TABLE PMH_GROUP_CATEGORY (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PARAM_NAME VARCHAR2(255 CHAR) NOT NULL,
    PARAM_VALUE VARCHAR2(255 CHAR) NOT NULL,
    PARAM_TYPE VARCHAR2(255 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(4000 CHAR),
    COMPONENT_CODE VARCHAR2(255 CHAR) NOT NULL,
    STATUS NUMBER(1) DEFAULT 1 NOT NULL, -- 1: Mới, 3: Chờ duyệt, 4: Đã duyệt, 5: Từ chối, 7: Hủy duyệt
    IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL, -- 0: Không hoạt động, 1: Hoạt động
    IS_DISPLAY NUMBER(1) DEFAULT 1 NOT NULL, -- 1: Chưa duyệt, 2: Đã duyệt
    NEW_DATA VARCHAR2(4000 CHAR), -- Lưu dữ liệu mới thay đổi dưới dạng JSON trước khi duyệt
    EFFECTIVE_DATE DATE NOT NULL,
    END_EFFECTIVE_DATE DATE,
    CREATED_BY VARCHAR2(50 CHAR),
    CREATED_DATE DATE DEFAULT SYSDATE,
    UPDATED_BY VARCHAR2(50 CHAR),
    UPDATED_DATE DATE DEFAULT SYSDATE
);

-- Ràng buộc độc nhất (Unique Constraint) cho bộ 3
ALTER TABLE PMH_GROUP_CATEGORY ADD CONSTRAINT UQ_GROUP_CATEGORY UNIQUE (PARAM_NAME, PARAM_VALUE, PARAM_TYPE);

-- Ràng buộc khóa ngoại (Foreign Key) tham chiếu cấu phần xử lý
ALTER TABLE PMH_GROUP_CATEGORY ADD CONSTRAINT FK_CATEGORY_COMPONENT 
FOREIGN KEY (COMPONENT_CODE) REFERENCES PMH_COMPONENTS(COMPONENT_CODE);


-- 3. Stored Procedure duyệt bản ghi (Dạng 3)
CREATE OR REPLACE PROCEDURE PROC_APPROVE_GROUP_CATEGORY (
    p_id IN NUMBER,
    p_user IN VARCHAR2,
    p_status OUT NUMBER,
    p_message OUT VARCHAR2
) AS
BEGIN
    UPDATE PMH_GROUP_CATEGORY
    SET STATUS = 4, -- Đã duyệt
        IS_DISPLAY = 2, -- Đã duyệt không cho phép xóa
        UPDATED_BY = p_user,
        UPDATED_DATE = SYSDATE
    WHERE ID = p_id;
    
    IF SQL%ROWCOUNT > 0 THEN
        p_status := 1;
        p_message := 'Duyệt thành công';
    ELSE
        p_status := 0;
        p_message := 'Không tìm thấy bản ghi';
    END IF;
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        p_status := -1;
        p_message := SQLERRM;
END;
/

-- 4. Stored Procedure từ chối duyệt (Dạng 3)
CREATE OR REPLACE PROCEDURE PROC_REJECT_GROUP_CATEGORY (
    p_id IN NUMBER,
