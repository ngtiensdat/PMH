-- 1. Bảng danh mục Chức năng nhỏ PMH_PERMISSIONS
CREATE TABLE PMH_PERMISSIONS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PERMISSION_CODE VARCHAR2(100 CHAR) NOT NULL UNIQUE,
    PERMISSION_NAME VARCHAR2(255 CHAR) NOT NULL,
    MODULE VARCHAR2(50 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(255 CHAR)
);

-- 2. Bảng nối gán Chức năng vào Vai trò PMH_ROLE_PERMISSIONS
CREATE TABLE PMH_ROLE_PERMISSIONS (
    ROLE_ID NUMBER NOT NULL,
    PERMISSION_ID NUMBER NOT NULL,
    CONSTRAINT PK_PMH_ROLE_PERMISSIONS PRIMARY KEY (ROLE_ID, PERMISSION_ID),
    CONSTRAINT FK_RP_ROLE FOREIGN KEY (ROLE_ID) REFERENCES PMH_ROLES(ID) ON DELETE CASCADE,
    CONSTRAINT FK_RP_PERM FOREIGN KEY (PERMISSION_ID) REFERENCES PMH_PERMISSIONS(ID) ON DELETE CASCADE
);

CREATE INDEX IDX_RP_ROLE_ID ON PMH_ROLE_PERMISSIONS(ROLE_ID);
CREATE INDEX IDX_RP_PERM_ID ON PMH_ROLE_PERMISSIONS(PERMISSION_ID);

