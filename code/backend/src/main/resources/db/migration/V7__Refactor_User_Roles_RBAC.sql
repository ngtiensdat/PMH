-- 1. Xóa các bảng cũ an toàn nếu đã có trong CSDL 
BEGIN
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE PMH_USER_ROLES CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE PMH_ROLES CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE PMH_APP_USERS CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
END;
;

-- 2. Tạo bảng người dùng PMH_APP_USERS (đã loại bỏ cột ROLE thừa)
CREATE TABLE PMH_APP_USERS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(50 CHAR) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR2(255 CHAR) NOT NULL,
    FULL_NAME VARCHAR2(100 CHAR),
    FAILED_LOGIN_ATTEMPTS NUMBER(10) DEFAULT 0 NOT NULL,
    LOCKOUT_UNTIL TIMESTAMP
);

-- 3. Tạo bảng danh mục vai trò PMH_ROLES
CREATE TABLE PMH_ROLES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ROLE_CODE VARCHAR2(50 CHAR) NOT NULL UNIQUE,
    ROLE_NAME VARCHAR2(100 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(255 CHAR)
);

-- 4. Tạo bảng nối quan hệ Nhiều - Nhiều PMH_USER_ROLES
CREATE TABLE PMH_USER_ROLES (
    USER_ID NUMBER NOT NULL,
    ROLE_ID NUMBER NOT NULL,
    ASSIGNED_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PMH_USER_ROLES PRIMARY KEY (USER_ID, ROLE_ID),
    CONSTRAINT FK_UR_USER FOREIGN KEY (USER_ID) REFERENCES PMH_APP_USERS(ID) ON DELETE CASCADE,
    CONSTRAINT FK_UR_ROLE FOREIGN KEY (ROLE_ID) REFERENCES PMH_ROLES(ID) ON DELETE CASCADE
);

CREATE INDEX IDX_UR_USER_ID ON PMH_USER_ROLES(USER_ID);
CREATE INDEX IDX_UR_ROLE_ID ON PMH_USER_ROLES(ROLE_ID);

